const REMOTE = /\b(remote|anywhere|distributed|work from home|wfh)\b/;

// Two-letter US state codes and "us" only count as the US when they are a separate word after a comma,
// e.g. "Austin, TX" or "Remote - US"; otherwise "co" or "ca" would match words in other places.
const SHORT_CODES = new Set([
  "us",
  "u s",
  "ca",
  "ny",
  "wa",
  "tx",
  "ma",
  "il",
  "co",
  "sf",
  "dc",
  "uk",
  "u k",
  "eu",
]);

function hasWord(text: string, word: string): boolean {
  return ` ${text} `.includes(` ${word} `);
}

/** Regions named in one location string, e.g. "Bengaluru, India" → ["in"], "Remote - US" → ["us", "remote"]. */
export function regionsOf(location: string | undefined | null): Region[] {
  if (!location) return [];
  const raw = location.toLowerCase();
  const n = norm(location);
  const out = new Set<Region>();
  if (REMOTE.test(raw)) out.add("remote");
  for (const [region, words] of Object.entries(WORDS) as [Exclude<Region, "remote">, string[]][]) {
    for (const w of words) {
      if (SHORT_CODES.has(w)) {
        // Only as its own token after a separator ("Austin, TX", "Remote - US", "London, UK").
        const tokens = raw.split(/[,;/()|\-–]+/).map((t) => t.trim().replace(/\./g, " ").trim());
        if (tokens.some((t) => t === w)) out.add(region);
      } else if (hasWord(n, norm(w))) out.add(region);
    }
  }
  // "Remote, Canada" etc. are fine; "Georgia" the country is rare in job posts, so it stays US.
  // "Cambridge, MA" is US; plain "Cambridge" stays unclassified.
  return [...out];
}

/** Regions a person wants to work in, from their locations and countries ("remote" stays remote). */
export function regionsForPlaces(places: string[]): Region[] {
  const out = new Set<Region>();
  for (const p of places) {
    const n = norm(p);
    const direct = (REGIONS as readonly string[]).includes(n) ? (n as Region) : undefined;
    if (direct) out.add(direct);
    for (const r of regionsOf(p)) out.add(r);
    if (n === "worldwide" || n === "global") out.add("remote");
  }
  return [...out];
}
