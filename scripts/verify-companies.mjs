#!/usr/bin/env node
// Builds data/companies.json, the starter company list, by checking each candidate against the public
// Greenhouse, Lever and Ashby job-board APIs (read-only GET requests, no login). Boards that do not exist or
// have no open jobs are dropped. Regions and job families come from the live job locations and titles.
//
//   npm run companies:verify                       # re-check scripts/company-candidates.json
//   npm run companies:verify -- --min-jobs 3       # keep boards with at least 3 open jobs
//
// Candidate entries: { "name": "Acme", "industry": "fintech", "size": "scaleup", "try": ["greenhouse:acme"] }
// Without "try", the script guesses slugs from the name on all three job sites.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { probeBoard } from "../dist/companies/probe.js";
import { defaultFetcher } from "../dist/sources/http.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const opt = (name, fallback) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : fallback;
};
const input = opt("--input", join(root, "scripts", "company-candidates.json"));
const output = opt("--output", join(root, "data", "companies.json"));
const minJobs = Number(opt("--min-jobs", "1"));
const concurrency = Number(opt("--concurrency", "6"));

const candidates = JSON.parse(readFileSync(input, "utf8"));

function guesses(name) {
  const base = name
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[^a-z0-9 ]+/g, "")
    .trim();
  const slugs = [...new Set([base.replace(/ +/g, ""), base.replace(/ +/g, "-")])];
  return ["greenhouse", "ashby", "lever"].flatMap((ats) => slugs.map((token) => `${ats}:${token}`));
}

async function firstWorking(tries, stopAtFirst) {
  let best;
  for (const t of tries) {
    const [ats, token] = t.split(":");
    try {
      const p = await probeBoard(defaultFetcher, ats, token);
      if (!best || p.jobs > best.jobs) best = p;
      if (stopAtFirst && p.jobs > 0) break; // an explicit token that works is the one we want
    } catch {
      // not on this ATS
    }
  }
  return best;
}

async function check(c) {
  const explicit = c.try?.length ? await firstWorking(c.try, true) : undefined;
  if (explicit?.jobs) return explicit;
  const tried = new Set(c.try ?? []);
  const guessed = await firstWorking(
    guesses(c.name).filter((t) => !tried.has(t)),
    false,
  );
  return guessed ? { ...guessed, guessed: true } : explicit;
}

const results = [];
const review = [];
let next = 0;
let done = 0;
async function worker() {
  while (next < candidates.length) {
    const c = candidates[next++];
    const p = await check(c);
    done++;
    if (p && p.jobs >= minJobs) {
      results.push({
        name: c.name,
        ats: p.ats,
        token: p.token,
        regions: p.regions,
        industry: c.industry,
        size: c.size,
        functions: p.functions.slice(0, 6),
        jobs: p.jobs,
      });
      review.push({
        name: c.name,
        ats: p.ats,
        token: p.token,
        boardName: p.name,
        guessed: !!p.guessed,
        sample: p.sample,
      });
      process.stdout.write(`✓ ${c.name} (${p.ats}:${p.token}) ${p.jobs} jobs [${p.regions.join(",")}]\n`);
    } else process.stdout.write(`✗ ${c.name}${p ? ` (${p.jobs} jobs)` : ""}\n`);
    if (done % 25 === 0) process.stderr.write(`  ${done}/${candidates.length}\n`);
  }
}
await Promise.all(Array.from({ length: concurrency }, worker));

results.sort((a, b) => a.name.localeCompare(b.name));
const out = {
  version: 1,
  checkedAt: new Date().toISOString().slice(0, 10),
  note: "Generated by scripts/verify-companies.mjs from the public Greenhouse, Lever and Ashby job-board APIs. 'jobs' is the open-job count on checkedAt; 'size' (startup <200, scaleup 200-2000, large 2000+) and 'industry' are approximate.",
  companies: results,
};
writeFileSync(output, `${JSON.stringify(out, null, 2)}\n`);
const reviewFile = opt("--review");
if (reviewFile) writeFileSync(reviewFile, `${JSON.stringify(review, null, 2)}\n`);
console.log(`\n${results.length} of ${candidates.length} candidates verified → ${output}`);
